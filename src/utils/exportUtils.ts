/**
 * Triggers a dedicated, clean, audit-grade Print dialog.
 * Opens an isolated clean document tailored specifically for PDF/paper print.
 */
export function triggerPrintReport(report: WorkbookAuditReport) {
  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    alert('Pop-up blocked! Please allow pop-ups for this site to print or save the PDF report, or use the "Download HTML / Markdown" option.');
    return;
  }
  printWindow.document.open();
  printWindow.document.write(generatePrintableHtml(report));
  printWindow.document.close();
}
