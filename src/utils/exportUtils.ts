/**
 * Formats bytes into a human-readable string.
 */
function formatBytes(bytes: number): string {
  if (bytes === 0) return '0 B';
  const k = 1024;
  const sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(1)) + ' ' + sizes[i];
}

/**
 * Generates a clean, professional Markdown audit report suitable for Slack, Notion, or GitHub.
 */
export function generateMarkdownReport(report: WorkbookAuditReport): string {
  const dateStr = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });

  const lines: string[] = [];

  lines.push(`# 🐕 SheetHound Audit Report: ${report.fileName}`);
  lines.push(`*Generated by SheetHound (by Utharam) on ${dateStr}*`);
  lines.push(`*Audited 100% in-browser with zero server uploads*\n`);

  lines.push(`---`);
  lines.push(`## 📊 Executive Summary`);
  lines.push(`- **Total Worksheets:** ${report.totalSheets} (${report.visibleSheetsCount} Visible, ${report.hiddenSheetsCount} Hidden, ${report.veryHiddenSheetsCount} Very Hidden)`);
  lines.push(`- **Total Formulas:** ${report.totalFormulas}`);
  lines.push(`- **Formula Errors Detected:** ${report.totalErrors}`);
  lines.push(`- **External Workbook References:** ${report.totalExternalLinks} across ${report.uniqueExternalFiles.length} file(s)`);
  lines.push(`- **Stray / Outlier Data Alerts:** ${report.strayDataWarningCount}`);
  lines.push(`- **Unique Fonts Used:** ${report.uniqueFontsCount}`);
  lines.push(`- **Unique Colors Used:** ${report.uniqueColorsCount}\n`);

  // External Links Section
  lines.push(`---`);
  lines.push(`## 🔗 External Links Registry (${report.totalExternalLinks})`);
  if (report.externalLinksRegistry.length === 0) {
    lines.push(`> ✅ **No external workbook links detected.** Safe to share externally without #REF! risks.\n`);
  } else {
    lines.push(`> ⚠️ **Warning:** The following cells reference external files. Opening this workbook on another machine will return \`#REF!\` unless broken/hardcoded.`);
    lines.push(`\n| Cell | Target Workbook | Target Range | Formula |`);
    lines.push(`| :--- | :--- | :--- | :--- |`);
    report.externalLinksRegistry.forEach((link) => {
      const loc = `${link.sheetName}!${link.cell}`;
      const target = `[${link.targetWorkbook}]`;
      const range = link.targetSheet ? `${link.targetSheet}!${link.targetRange || ''}` : '—';
      const formula = link.formula.startsWith('=') ? link.formula : `=${link.formula}`;
      lines.push(`| \`${loc}\` | **${target}** | \`${range}\` | \`${formula}\` |`);
    });
    lines.push(``);
  }

  // Formula Errors Section
  lines.push(`---`);
  lines.push(`## 💥 Formula Errors Registry (${report.totalErrors})`);
  if (report.errorsRegistry.length === 0) {
    lines.push(`> ✅ **Zero formula evaluation errors detected.** All calculated formulas evaluated cleanly.\n`);
  } else {
    lines.push(`\n| Cell | Error Type | Formula | Value |`);
    lines.push(`| :--- | :--- | :--- | :--- |`);
    report.errorsRegistry.forEach((err) => {
      const loc = `${err.sheetName}!${err.cell}`;
      const formula = err.formula ? (err.formula.startsWith('=') ? err.formula : `=${err.formula}`) : '—';
      lines.push(`| \`${loc}\` | **${err.errorType}** | \`${formula}\` | \`${err.cachedValue || err.errorType}\` |`);
    });
    lines.push(``);
  }

  // Worksheets & Stray Data Section
  lines.push(`---`);
  lines.push(`## 📑 Worksheets & Spatial Density Breakdown`);
  lines.push(`\n| Sheet Name | State | Boundary | Farthest Cell | Spatial Cluster / Stray Status | Errors |`);
  lines.push(`| :--- | :--- | :--- | :--- | :--- | :--- |`);
  report.sheets.forEach((s) => {
    const clusterStr = s.heatmap ? `${s.heatmap.mainClusterBounds.colStartLetter}${s.heatmap.mainClusterBounds.rowStart}..${s.heatmap.mainClusterBounds.colEndLetter}${s.heatmap.mainClusterBounds.rowEnd} (${s.heatmap.mainClusterBounds.percentageOfData}%)` : '—';
    const strayStr = s.boundary.hasStrayCells ? `⚠️ **STRAY OUTLIER** (${s.boundary.farthestCell})` : `✓ Clustered (${clusterStr})`;
    lines.push(`| **${s.name}** | \`${s.visibility}\` | \`Row 1..${s.boundary.maxRow}, Col 1..${s.boundary.maxCol}\` | \`${s.boundary.farthestCell}\` | ${strayStr} | ${s.errorCount} |`);
  });
  lines.push(``);

  // Design Section
  lines.push(`---`);
  lines.push(`## 🎨 Typography & Brand Colors`);
  lines.push(`- **Fonts:** ${report.fontInventory.map((f) => `\`${f.name}\` (${f.count} cells)`).join(', ')}`);
  lines.push(`- **Color Palette (Top 6):** ${report.colorPalette.slice(0, 6).map((c) => `\`${c.hex}\` (${c.count} cells)`).join(', ')}\n`);

  lines.push(`---`);
  lines.push(`*Audited by SheetHound • by Utharam (https://utharam.github.io/) • Dedicated to Veeran the Indian Spitz 🐾*`);

  return lines.join('\n');
}

