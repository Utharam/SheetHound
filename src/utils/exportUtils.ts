/**
 * Triggers a browser file download for a generated string.
 */
export function triggerFileDownload(content: string, fileName: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Exports JSON audit data.
 */
export function exportJsonReport(report: WorkbookAuditReport) {
  const jsonStr = JSON.stringify(report, null, 2);
  const cleanName = report.fileName.replace(/\.[^/.]+$/, '');
  triggerFileDownload(jsonStr, `${cleanName}-SheetHound-Audit.json`, 'application/json');
}

